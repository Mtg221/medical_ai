def build_all_templates() -> list[TemplateSpec]:
    """Return all 640+ TemplateSpec objects across EN/FR and all 8 sections."""
    section_map_en = {
        "header": _EN_HEADER,
        "chief_complaint": _EN_CHIEF_COMPLAINT,
        "history": _EN_HISTORY,
        "hpi": _EN_HPI,
        "medications": _EN_MEDICATIONS,
        "labs": _EN_LABS,
        "assessment": _EN_ASSESSMENT,
        "plan": _EN_PLAN,
    }
    section_map_fr = {
        "header": _FR_HEADER,
        "chief_complaint": _FR_CHIEF_COMPLAINT,
        "history": _FR_HISTORY,
        "hpi": _FR_HPI,
        "medications": _FR_MEDICATIONS,
        "labs": _FR_LABS,
        "assessment": _FR_ASSESSMENT,
        "plan": _FR_PLAN,
    }
    specs: list[TemplateSpec] = []
    for lang, smap in (("en", section_map_en), ("fr", section_map_fr)):
        for sec, patterns in smap.items():
            for idx, pat in enumerate(patterns, start=1):
                specs.append(TemplateSpec(f"{lang}_{sec}_{idx:02d}", sec, lang, pat))
    return specs


def partition_templates(
    specs: list[TemplateSpec],
    *,
    unseen_ratio: float = 0.30,
    seed: int = 42,
) -> tuple[dict[tuple[str, str], list[TemplateSpec]], dict[tuple[str, str], list[TemplateSpec]]]:
    """Split templates 70/30 per (language, section) into (seen, unseen) dicts."""
    from collections import defaultdict

    grouped: dict[tuple[str, str], list[TemplateSpec]] = defaultdict(list)
    for sp in specs:
        grouped[(sp.language, sp.section)].append(sp)

    rng = random.Random(seed)
    seen: dict[tuple[str, str], list[TemplateSpec]] = {}
    unseen: dict[tuple[str, str], list[TemplateSpec]] = {}
    for key in sorted(grouped.keys()):
        items = list(grouped[key])
        rng.shuffle(items)
        n_unseen = max(1, round(len(items) * unseen_ratio))
        unseen[key] = items[:n_unseen]
        seen[key] = items[n_unseen:]
    return seen, unseen
