def partition_concepts(
    items: tuple[LexiconEntry, ...] | tuple[MedEntry, ...] | tuple[LabEntry, ...],
    *,
    unseen_ratio: float = 0.30,
    seed: int = 42,
) -> tuple[list[Any], list[Any]]:
    """Deterministically split concept IDs into (seen_70%, unseen_30%) so all variants stay together."""
    cids = sorted({item.concept_id for item in items})
    rng = random.Random(seed)
    rng.shuffle(cids)
    n_unseen = max(1, round(len(cids) * unseen_ratio))
    unseen_set = set(cids[:n_unseen])
    seen: list[Any] = [item for item in items if item.concept_id not in unseen_set]
    unseen: list[Any] = [item for item in items if item.concept_id in unseen_set]
    return seen, unseen
