"""Inspect all 14 raw derm manifest pages and generate `docs/data/DERM_FIELDS.md` (Step 2 / W1 / W4)."""

from __future__ import annotations

import json
import re
from collections import Counter, defaultdict
from pathlib import Path

FIELD_DESCRIPTIONS: dict[str, str] = {
    "i": "Unique record ID (`<dataset>:<id>`)",
    "d": "Dataset name (`isic`, `fitzpatrick17k`, `scin`, `skindisnet`, ...)",
    "t": "Relative thumbnail path (`.webp`)",
    "f": "Relative raw image path (`.jpg` / `.png`)",
    "st": "Fitzpatrick skin tone (`I`..`VI`)",
    "ss": "Skin tone source (`estimated`, `self_reported`, `unknown`)",
    "mk": "Metadata key (in `scin`: rater country counts like `us=3;india=3`; in `isic`: `None`)",
    "dx": "Raw diagnosis label / dict",
    "mg": "Malignancy group (`benign`, `malignant`, `unknown`, `indeterminate`)",
    "bs": "Body site (`loc` / anatomical location)",
    "cc": "Country code (e.g. `US`)",
    "lc": "License string (`CC-BY`, `CC-BY-NC-4.0`, `SCIN-Data-Use-Public-License`, ...)",
    "ok": "Upstream redistribution/commercial-OK flag (`true`/`false`, mapped to `quality_ok` in `catalog.py`)",
    "rd": "Research/redistribution allowed boolean",
    "cf": "Confirmation method (`histopathology`, `serial imaging showing no change`, ...)",
}


def _is_filled(val: object) -> bool:
    if val is None:
        return False
    if isinstance(val, str):
        return val.strip() != "" and val.strip().lower() not in ("unknown", "none", "null", "nan")
    if isinstance(val, (list, dict, set)):
        return len(val) > 0
    return True


def _infer_mod(fname: str) -> str:
    for m in ("clinical", "dermoscopic", "tbp_tile"):
        if m in fname:
            return m
    return "unknown"


def inspect_manifests(
    meta_dir: str | Path = "var/cache/derm/meta",
    out_md: str | Path = "docs/data/DERM_FIELDS.md",
) -> dict[str, object]:
    meta_path = Path(meta_dir)
    manifest_files = sorted(
        [
            p
            for p in meta_path.glob("manifest*.json")
            if p.name != "sync_manifest.json"
        ]
    )

    all_keys: set[str] = set()
    ds_totals: Counter[str] = Counter()
    ds_field_fills: dict[str, Counter[str]] = defaultdict(Counter)
    ds_ok_counts: dict[str, Counter[str]] = defaultdict(Counter)
    ds_rd_counts: dict[str, Counter[str]] = defaultdict(Counter)
    ds_lic_counts: dict[str, Counter[str]] = defaultdict(Counter)
    ds_mod_counts: dict[str, Counter[str]] = defaultdict(Counter)
    ds_mg_counts: dict[str, Counter[str]] = defaultdict(Counter)
    ds_sample_records: dict[str, list[dict[str, object]]] = defaultdict(list)
    file_summaries: list[tuple[str, int, dict[str, int]]] = []

    for mf in manifest_files:
        payload = json.loads(mf.read_text(encoding="utf-8"))
        items = payload.get("items")
        if not isinstance(items, list):
            file_summaries.append((mf.name, 0, {}))
            continue
        mod = _infer_mod(mf.name)
        file_ds: Counter[str] = Counter()
        for rec in items:
            if not isinstance(rec, dict):
                continue
            ds = str(rec.get("d") or "UNKNOWN")
            ds_totals[ds] += 1
            file_ds[ds] += 1
            all_keys.update(rec.keys())
            for k, v in rec.items():
                if _is_filled(v):
                    ds_field_fills[ds][k] += 1
            ok_val = rec.get("ok")
            ok_key = "true" if ok_val is True else ("false" if ok_val is False else f"other:{ok_val}")
            ds_ok_counts[ds][ok_key] += 1
            rd_val = rec.get("rd")
            rd_key = "true" if rd_val is True else ("false" if rd_val is False else f"other:{rd_val}")
            ds_rd_counts[ds][rd_key] += 1
            ds_lic_counts[ds][str(rec.get("lc") or "MISSING")] += 1
            ds_mod_counts[ds][mod] += 1
            ds_mg_counts[ds][str(rec.get("mg") or "MISSING")] += 1
            if len(ds_sample_records[ds]) < 2:
                ds_sample_records[ds].append(
                    {
                        "i": rec.get("i"),
                        "f": rec.get("f"),
                        "mk": rec.get("mk"),
                        "lc": rec.get("lc"),
                        "ok": rec.get("ok"),
                        "rd": rec.get("rd"),
                        "cf": rec.get("cf"),
                    }
                )
        file_summaries.append((mf.name, len(items), dict(file_ds)))

    datasets = sorted(ds_totals.keys())
    sorted_keys = sorted(all_keys)
    total_records = sum(ds_totals.values())

    lines: list[str] = [
        "# Dermatology Raw Manifest Field & Linking Audit (`DERM_FIELDS.md`)",
        "",
        "> Generated by `scripts/inspect_derm_fields.py` across all 14 manifest pages in `var/cache/derm/meta/` (Step 2 / W1 / W4).",
        "",
        f"- **Total manifest files inspected:** `{len(manifest_files)}` (`manifest.json` index + 13 shard pages)",
        f"- **Total item records:** `{total_records:,}`",
        f"- **Distinct datasets (`d`):** {', '.join(f'`{d}` (`{ds_totals[d]:,}`)' for d in datasets)}",
        "",
        "## 1. Manifest Pages Summary",
        "",
        "| File | Records | Dataset Breakdown (`d`) |",
        "|---|---|---|",
    ]
    for fname, cnt, fds in file_summaries:
        ds_str = ", ".join(f"`{k}`: {v:,}" for k, v in sorted(fds.items())) if fds else "*(top-level index manifest)*"
        lines.append(f"| `{fname}` | `{cnt:,}` | {ds_str} |")

    lines.extend([
        "",
        "## 2. Every Field Name & Fill Rate per Dataset",
        "",
        "Non-empty, non-`unknown`/`none`/`null` fill counts and percentages:",
        "",
        "| Field | Meaning | " + " | ".join(f"`{d}` (`n={ds_totals[d]:,}`)" for d in datasets) + " |",
        "|---|---|" + "|".join("---" for _ in datasets) + "|",
    ])
    for k in sorted_keys:
        desc = FIELD_DESCRIPTIONS.get(k, "—")
        cells = []
        for d in datasets:
            cnt = ds_field_fills[d][k]
            pct = (100.0 * cnt / ds_totals[d]) if ds_totals[d] else 0.0
            cells.append(f"`{cnt:,}` ({pct:.1f}%)")
        lines.append(f"| `{k}` | {desc} | " + " | ".join(cells) + " |")

    lines.extend([
        "",
        "## 3. W4 Audit: `ok`, `rd`, and `lc` (License) per Dataset",
        "",
        "| Dataset | Total | `ok == true` | `ok == false` | `rd == true` | Licenses (`lc`) | Modalities (`mod`) | Malignancy (`mg`) |",
        "|---|---|---|---|---|---|---|---|",
    ])
    for d in datasets:
        ok_t = ds_ok_counts[d]["true"]
        ok_f = ds_ok_counts[d]["false"]
        rd_t = ds_rd_counts[d]["true"]
        lic_s = ", ".join(f"`{k}`: {v:,}" for k, v in ds_lic_counts[d].most_common(6))
        mod_s = ", ".join(f"`{k}`: {v:,}" for k, v in ds_mod_counts[d].most_common(4))
        mg_s = ", ".join(f"`{k}`: {v:,}" for k, v in ds_mg_counts[d].most_common(5))
        lines.append(
            f"| `{d}` | `{ds_totals[d]:,}` | `{ok_t:,}` | `{ok_f:,}` | `{rd_t:,}` | {lic_s} | {mod_s} | {mg_s} |"
        )

    lines.extend([
        "",
        "### Why Fitzpatrick17k and SCIN Were Dropped (W4)",
        "",
        "- **Verified in code:** `catalog.py` line 108 reads `quality_ok = bool(row.get(\"ok\", False))` straight from the manifest, and `sync.py` calls the catalog with `require_quality_ok=True`. Any record with `ok == false` is therefore excluded from every split.",
        "- **Verified in the data (table above):** `ok == false` for **100% of `fitzpatrick17k` (11,394)** and **100% of `scin` (10,379)**, and for **245,287 ISIC records, exactly the number of `CC-BY-NC` ISIC records**. `rd == true` for every record.",
        "- **NOT verified:** what `ok` means upstream. The manifest has no documentation for it. The pattern (all `CC-BY-NC` ISIC, all Fitzpatrick17k `CC-BY-NC-4.0`, all SCIN) fits a licence/clearance flag rather than an image-quality check, but this is an inference. The sync code and report call it `quality`, so the label is misleading either way.",
        "- **Label availability if they were included:** `fitzpatrick17k` has `mg` filled for 3,190 / 11,394 records (28.0%); `scin` has `mg` filled for **0** records (every `mg` is `unknown`, only `dx` probabilities exist); `skindisnet` has `mg` filled for **0**. So SCIN would add skin-tone coverage (`st` filled for 91.9%) but **no malignancy labels** without a diagnosis-to-malignancy mapping.",
        "- **Owner Decision Needed (Part D #2):** include `fitzpatrick17k` / `scin` (and/or the `CC-BY-NC` ISIC records) for **local non-commercial research** (no redistribution, no screenshots), or keep them excluded?",
        "",
        "## 4. Lesion / Patient Grouping Signals Inspection (W1)",
        "",
        "- **Explicit lesion/patient key (`mk`):** `0` records in `isic` or `fitzpatrick17k` or `skindisnet` have a lesion/patient `mk`. In `scin`, `mk` is populated (99.8%) with **country rater counts** (e.g. `'us=3;india=3'`), NOT a patient/lesion ID.",
        "- **Image IDs (`i`) and raw filenames (`f`):**",
    ])
    for d in datasets:
        previews = []
        for s in ds_sample_records[d]:
            previews.append(f"`i={s['i']}`, `f={re.sub(r'[|`]', '', str(s['f']))}`, `mk={s['mk']}`")
        lines.append(f"  - **`{d}`**: " + " ; ".join(previews))
    lines.extend([
        "",
        "- **Implication for Step 2 / `locked_test_v3` grouping:** Because the raw manifests contain **zero** explicit `lesion_id` or `patient_id` fields across all 573,024 records, grouping must use a **pixel + metadata similarity grouping** (`PyTorchDermResNet` penultimate embedding cosine similarity + `dHash <= 10` + same `mod`/`bs`/`dx`) so near-duplicate and visually similar serial/tile photos of the same lesion/patient stay in the same split.",
    ])

    out_path = Path(out_md)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return {
        "total_records": total_records,
        "datasets": dict(ds_totals),
        "fields": sorted_keys,
        "ok_counts": {d: dict(ds_ok_counts[d]) for d in datasets},
        "lic_counts": {d: dict(ds_lic_counts[d]) for d in datasets},
        "out_md": str(out_path),
    }


if __name__ == "__main__":
    summary = inspect_manifests()
    print(json.dumps(summary, indent=2))
